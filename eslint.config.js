// The rule that matters here is the Prisma import ban. Everything else is
// standard Next.js linting.
//
// Keeping database access inside lib/queries/ is the one architectural
// boundary we cannot enforce by convention alone — it is too easy to reach
// for `prisma` in a component and have it work. So it fails the build.

import js from "@eslint/js";
import next from "@next/eslint-plugin-next";
import tseslint from "typescript-eslint";

export default [
  js.configs.recommended,
  ...tseslint.configs.recommended,
  {
    plugins: { "@next/next": next },
    rules: {
      ...next.configs.recommended.rules,
      "@typescript-eslint/no-explicit-any": "off",
      "@typescript-eslint/no-unused-vars": [
        "warn",
        { argsIgnorePattern: "^_" },
      ],
    },
  },
  {
    // Prisma is allowed only in lib/queries/ and prisma/seed.ts.
    //
    // lib/auth.ts is the one exception: the Auth.js Prisma adapter takes a
    // client instance, and Account/Session/VerificationToken are written by the
    // adapter rather than by us. It holds no queries of our own.
    ignores: ["lib/queries/**", "lib/db.ts", "lib/auth.ts", "prisma/**"],
    rules: {
      "no-restricted-imports": [
        "error",
        {
          paths: [
            {
              name: "@prisma/client",
              message:
                "Database access belongs in lib/queries/. Import a query function instead. See docs/ARCHITECTURE.md.",
            },
            {
              name: "@/lib/db",
              message:
                "Database access belongs in lib/queries/. Import a query function instead. See docs/ARCHITECTURE.md.",
            },
          ],
        },
      ],
    },
  },
  {
    // Scoring stays pure so it can be tested without a database.
    files: ["lib/scoring/**"],
    rules: {
      "no-restricted-imports": [
        "error",
        {
          patterns: [
            {
              group: ["@/lib/queries/*", "@prisma/client", "react", "next/*"],
              message:
                "lib/scoring/ is pure functions. It takes data and returns data.",
            },
          ],
        },
      ],
    },
  },
  {
    // next-env.d.ts is generated by Next and is not ours to fix.
    ignores: [
      ".next/**",
      "node_modules/**",
      "components/ui/**",
      "next-env.d.ts",
    ],
  },
];
